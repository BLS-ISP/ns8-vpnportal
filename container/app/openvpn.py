PROC_DISABLE_IPV6_PATH = Path("/proc/sys/net/ipv6/conf/all/disable_ipv6")
PROC_BINDV6ONLY_PATH = Path("/proc/sys/net/ipv6/bindv6only")


def detect_host_ipv6_dualstack(
    *,
    disable_ipv6_path: Path | None = None,
    bindv6only_path: Path | None = None,
) -> bool:
    """Return True on Linux when IPv6 is enabled AND `bindv6only=0` dual-stack sockets are active."""
    disable_path = disable_ipv6_path or PROC_DISABLE_IPV6_PATH
    v6only_path = bindv6only_path or PROC_BINDV6ONLY_PATH
    try:
        disable_val = disable_path.read_text(encoding="utf-8").strip()
        bindv6_val = v6only_path.read_text(encoding="utf-8").strip()
    except OSError:
        return False
    return disable_val == "0" and bindv6_val == "0"


def validate_openvpn_settings(
    *,
    ovpn_enabled: bool,
    ovpn_proto: str,
    ovpn_port: int,
    ovpn_public_port: int,
    ovpn_network: str,
    wg_port: int,
    wg_network: str,
    allowed_cidrs: list[str],
    cluster_wg_cidr: str = DEFAULT_CLUSTER_WG_CIDR,
    cluster_wg_port: int = DEFAULT_CLUSTER_WG_PORT,
) -> tuple[str, int, int, str]:
    """Validate OpenVPN network/port settings against WireGuard, cluster `wg0`, and LAN CIDRs."""
    proto = (ovpn_proto or "tcp").strip().lower()
    if proto not in {"tcp", "udp"}:
        raise IPAMValidationError("ovpn_proto must be 'tcp' or 'udp'")

    for field_name, pval in (("ovpn_port", ovpn_port), ("ovpn_public_port", ovpn_public_port)):
        if isinstance(pval, bool) or not isinstance(pval, int) or pval < 1 or pval > 65535:
            raise IPAMValidationError(f"{field_name} must be an integer between 1 and 65535")

    if proto == "udp":
        if ovpn_port in {DEFAULT_CLUSTER_WG_PORT, cluster_wg_port}:
            raise IPAMValidationError(
                f"ovpn_port {ovpn_port}/udp is reserved for NS8 cluster WireGuard (wg0)"
            )
        if ovpn_port == wg_port:
            raise IPAMValidationError(
                f"ovpn_port {ovpn_port}/udp collides with WireGuard wg_port {wg_port}/udp"
            )

    net = normalize_wg_network(ovpn_network, cluster_wg_cidr=cluster_wg_cidr)
    wg_net = normalize_wg_network(wg_network, cluster_wg_cidr=cluster_wg_cidr)
    if net.overlaps(wg_net):
        raise IPAMValidationError(
            f"ovpn_network {net} overlaps WireGuard transfer network {wg_net}"
        )

    if ovpn_enabled:
        for cidr_str in allowed_cidrs:
            allowed_net = ipaddress.ip_network(cidr_str, strict=False)
            if isinstance(allowed_net, ipaddress.IPv4Network) and net.overlaps(allowed_net):
                raise IPAMValidationError(
                    f"ovpn_network {net} overlaps Split-Tunnel allowed CIDR {allowed_net}"
                )

    return proto, int(ovpn_port), int(ovpn_public_port), str(net)


def render_openvpn_server_conf(
    *,
    interface_name: str,
    ovpn_proto: str,
    ovpn_port: int,
    ovpn_network: str,
    tunnel_mode: str,
    allowed_cidrs: list[str],
    dns_servers: list[str],
    dns_search_domain: str,
    pki: OpenVPNPKIBundle,
    mgmt_sock_path: Path | str,
    status_log_path: Path | str,
    admin_sock_path: Path | str | None = None,
    auth_script_path: str = "/app/openvpn_auth.py",
    ipv6_dualstack: bool | None = None,
) -> str:
    """Render hardened OpenVPN 2.6 server configuration with inline PKI & `tls-crypt`."""
    net = ipaddress.IPv4Network(ovpn_network, strict=False)
    use_dualstack = (
        detect_host_ipv6_dualstack() if ipv6_dualstack is None else bool(ipv6_dualstack)
    )
    if ovpn_proto == "tcp":
        proto_directive = "tcp6-server" if use_dualstack else "tcp-server"
    else:
        proto_directive = "udp6" if use_dualstack else "udp"
    mgmt_path_obj = Path(mgmt_sock_path)
    resolved_admin_sock = (
        Path(admin_sock_path) if admin_sock_path is not None else (mgmt_path_obj.parent / "admin.sock")
    )

    lines: list[str] = [
        "# Autogenerated by ns8-vpn controller",
        f"dev {interface_name}",
        "dev-type tun",
        f"proto {proto_directive}",
        f"port {int(ovpn_port)}",
        "topology subnet",
        f"server {net.network_address} {net.netmask}",
        "keepalive 10 60",
        "persist-key",
        "persist-tun",
        "dh none",
        "ecdh-curve prime256v1",
        "tls-version-min 1.2",
        "data-ciphers AES-256-GCM:CHACHA20-POLY1305",
        "auth SHA256",
        "verify-client-cert require",
        "username-as-common-name",
        "duplicate-cn",
        "script-security 2",
        f"setenv ADMIN_SOCK_PATH {resolved_admin_sock.as_posix()}",
        f"auth-user-pass-verify {auth_script_path} via-file",
        "reneg-sec 28800",
        f"management {mgmt_path_obj.as_posix()} unix",
        f"status {Path(status_log_path).as_posix()} 10",
        "status-version 2",
        "verb 3",
    ]

    if tunnel_mode == "full":
        lines.append('push "redirect-gateway def1 bypass-dhcp"')
    else:
        for cidr in allowed_cidrs:
            route_net = ipaddress.IPv4Network(cidr, strict=False)
            lines.append(f'push "route {route_net.network_address} {route_net.netmask}"')

    for dns_ip in dns_servers:
        lines.append(f'push "dhcp-option DNS {dns_ip}"')
    if (dns_search_domain or "").strip():
        lines.append(f'push "dhcp-option DOMAIN {dns_search_domain.strip()}"')

    lines.extend(
        [
            "",
            "<ca>",
            pki.ca_cert_pem.strip(),
            "</ca>",
            "<cert>",
            pki.server_cert_pem.strip(),
            "</cert>",
            "<key>",
            pki.server_key_pem.strip(),
            "</key>",
            "<tls-crypt>",
            pki.tls_crypt_key.strip(),
            "</tls-crypt>",
        ]
    )
    return "\n".join(lines) + "\n"


def render_openvpn_client_profile(
    *,
    endpoint_host: str,
    ovpn_public_port: int,
    ovpn_proto: str,
    pki: OpenVPNPKIBundle,
) -> str:
    """Render ready-to-import `.ovpn` client profile for OpenVPN Connect / desktop clients."""
    host = (endpoint_host or "").strip() or "vpn.example.com"
    proto_directive = "tcp-client" if ovpn_proto == "tcp" else "udp"

    lines = [
        "client",
        "dev tun",
        f"proto {proto_directive}",
        f"remote {host} {int(ovpn_public_port)}",
        "resolv-retry infinite",
        "nobind",
        "persist-key",
        "persist-tun",
        "remote-cert-tls server",
        "auth-user-pass",
        "auth-nocache",
        "tls-version-min 1.2",
        "data-ciphers AES-256-GCM:CHACHA20-POLY1305",
        "auth SHA256",
        "verb 3",
        "",
        "<ca>",
        pki.ca_cert_pem.strip(),
        "</ca>",
        "<cert>",
        pki.client_cert_pem.strip(),
        "</cert>",
        "<key>",
        pki.client_key_pem.strip(),
        "</key>",
        "<tls-crypt>",
        pki.tls_crypt_key.strip(),
        "</tls-crypt>",
    ]
    return "\n".join(lines) + "\n"


def sanitize_profile_filename(raw: str) -> str:
    clean = re.sub(r"[^A-Za-z0-9._-]+", "-", (raw or "").strip()).strip("-")
    return clean or "vpn"


def parse_openvpn_status_log(status_text: str) -> list[dict[str, Any]]:
    """Parse connected clients from OpenVPN status log (v1 or status-version 2/3)."""
    clients: list[dict[str, Any]] = []
    if not status_text:
        return clients

    lines = status_text.splitlines()
    # Check status-version 2/3 (`CLIENT_LIST,...` or `CLIENT_LIST\t...`)
    has_v2_header = any(
        line.startswith(("TITLE,", "TITLE\t", "CLIENT_LIST,", "CLIENT_LIST\t"))
        for line in lines
    )
    if has_v2_header:
        for line in lines:
            if line.startswith("CLIENT_LIST\t"):
                parts = line.split("\t")
            elif line.startswith("CLIENT_LIST,"):
                parts = line.split(",")
            else:
                continue
            if len(parts) < 6:
                continue
            cn = parts[1].strip()
            if not cn or cn == "UNDEF":
                continue
            clients.append(
                {
                    "username": cn,
                    "real_address": parts[2].strip(),
                    "virtual_address": parts[3].strip(),
                    "rx_bytes": int(parts[5]) if parts[5].strip().isdigit() else 0,
                    "tx_bytes": int(parts[6]) if len(parts) > 6 and parts[6].strip().isdigit() else 0,
                }
            )
        return clients

    # Fallback: OpenVPN status v1
    in_clients = False
    for line in lines:
        stripped = line.strip()
        if stripped.startswith("Common Name,Real Address"):
            in_clients = True
            continue
        if stripped.startswith("ROUTING TABLE") or stripped.startswith("GLOBAL STATS"):
            in_clients = False
            continue
        if in_clients and "," in stripped:
            parts = stripped.split(",")
            if len(parts) >= 4 and parts[0].strip() and parts[0].strip() != "UNDEF":
                clients.append(
                    {
                        "username": parts[0].strip(),
                        "real_address": parts[1].strip(),
                        "virtual_address": "",
                        "rx_bytes": int(parts[2]) if parts[2].strip().isdigit() else 0,
                        "tx_bytes": int(parts[3]) if parts[3].strip().isdigit() else 0,
                    }
                )
    return clients


class OpenVPNProcessController(Protocol):
    """Injectable daemon & management socket interface for OpenVPN."""

    def start_or_reload(
        self,
        conf_path: Path,
        pid_path: Path,
        rendered_conf: str,
        mgmt_sock_path: Path | None = None,
    ) -> None: ...

    def stop(self, pid_path: Path, mgmt_sock_path: Path | None = None) -> None: ...

    def is_running(self, pid_path: Path) -> bool: ...

    def kill_client(self, mgmt_sock_path: Path, username: str) -> bool: ...


class SubprocessOpenVPNController:
    """Supervises a real `openvpn` daemon process inside the container."""

    def __init__(self) -> None:
        self._proc: subprocess.Popen[bytes] | None = None
        self._last_conf: str | None = None

    def is_running(self, pid_path: Path) -> bool:
        if self._proc is not None and self._proc.poll() is None:
            return True
        if pid_path.is_file():
            try:
                pid = int(pid_path.read_text(encoding="utf-8").strip())
                os.kill(pid, 0)
                return True
            except (ValueError, OSError):
                return False
        return False

    def stop(self, pid_path: Path, mgmt_sock_path: Path | None = None) -> None:
        if self._proc is not None and self._proc.poll() is None:
            self._proc.terminate()
            try:
                self._proc.wait(timeout=5)
            except subprocess.TimeoutExpired:
                self._proc.kill()
        self._proc = None

        if pid_path.is_file():
            try:
                pid = int(pid_path.read_text(encoding="utf-8").strip())
                os.kill(pid, signal.SIGTERM)
            except (ValueError, OSError):
                pass
            pid_path.unlink(missing_ok=True)
        if mgmt_sock_path is not None:
            mgmt_sock_path.unlink(missing_ok=True)
        self._last_conf = None

    def start_or_reload(
        self,
        conf_path: Path,
        pid_path: Path,
        rendered_conf: str,
        mgmt_sock_path: Path | None = None,
    ) -> None:
        if self.is_running(pid_path) and self._last_conf == rendered_conf:
            return
        self.stop(pid_path, mgmt_sock_path=mgmt_sock_path)
        if mgmt_sock_path is not None:
            mgmt_sock_path.unlink(missing_ok=True)
        self._proc = subprocess.Popen(
            [
                "openvpn",
                "--config",
                str(conf_path),
                "--writepid",
                str(pid_path),
            ],
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
        )
        self._last_conf = rendered_conf

    def kill_client(self, mgmt_sock_path: Path, username: str) -> bool:
        safe_user = re.sub(r"[\r\n\x00]", "", (username or "").strip())
        if not safe_user or not mgmt_sock_path.exists():
            return False
        af_unix = getattr(socket, "AF_UNIX", None)
        if af_unix is None:
            return False
        sock = socket.socket(af_unix, socket.SOCK_STREAM)
        sock.settimeout(3.0)
        try:
            sock.connect(str(mgmt_sock_path))
            try:
                sock.recv(1024)
            except OSError:
                pass
            sock.sendall(f"kill {safe_user}\nquit\n".encode("utf-8"))
            resp = sock.recv(2048).decode("utf-8", errors="replace")
            return "SUCCESS:" in resp or "client(s) killed" in resp
        except OSError as exc:
            logger.debug("OpenVPN management socket kill skipped: %s", exc)
            return False
        finally:
            sock.close()


@dataclass
class DryRunOpenVPNController:
    """In-memory OpenVPN daemon & management-socket test double for CI/Windows."""

    running: bool = False
    last_conf: str = ""
    start_count: int = 0
    stop_count: int = 0
    killed_users: list[str] = field(default_factory=list)

    def start_or_reload(
        self,
        conf_path: Path,
        pid_path: Path,
        rendered_conf: str,
        mgmt_sock_path: Path | None = None,
    ) -> None:
        if self.running and self.last_conf == rendered_conf:
            return
        if mgmt_sock_path is not None:
            mgmt_sock_path.unlink(missing_ok=True)
        self.running = True
        self.last_conf = rendered_conf
        self.start_count += 1
        pid_path.write_text("99999\n", encoding="utf-8", newline="\n")

    def stop(self, pid_path: Path, mgmt_sock_path: Path | None = None) -> None:
        if self.running:
            self.stop_count += 1
        self.running = False
        self.last_conf = ""
        pid_path.unlink(missing_ok=True)
        if mgmt_sock_path is not None:
            mgmt_sock_path.unlink(missing_ok=True)

    def is_running(self, pid_path: Path) -> bool:
        return self.running

    def kill_client(self, mgmt_sock_path: Path, username: str) -> bool:
        safe_user = re.sub(r"[\r\n\x00]", "", (username or "").strip())
        if not safe_user:
            return False
        self.killed_users.append(safe_user)
        return True


class OpenVPNEngine:
    """Manages OpenVPN PKI, server configuration, process lifecycle, status, and session eviction."""

    def __init__(
        self,
        *,
        conf_path: Path,
        mgmt_sock_path: Path,
        status_log_path: Path,
        pid_path: Path,
        process_controller: OpenVPNProcessController,
        admin_sock_path: Path | None = None,
        ipv6_dualstack: bool | None = None,
    ) -> None:
        self.conf_path = conf_path
        self.mgmt_sock_path = mgmt_sock_path
        self.status_log_path = status_log_path
        self.pid_path = pid_path
        self.controller = process_controller
        self.admin_sock_path = admin_sock_path or (mgmt_sock_path.parent / "admin.sock")
        self.ipv6_dualstack = ipv6_dualstack

    def reconcile(
        self,
        *,
        ovpn_enabled: bool,
        interface_name: str,
        ovpn_proto: str,
        ovpn_port: int,
        ovpn_network: str,
        tunnel_mode: str,
        allowed_cidrs: list[str],
        dns_servers: list[str],
        dns_search_domain: str,
        pki: OpenVPNPKIBundle | None,
        ipv6_dualstack: bool | None = None,
    ) -> None:
        if not ovpn_enabled:
            self.controller.stop(self.pid_path, mgmt_sock_path=self.mgmt_sock_path)
            self.mgmt_sock_path.unlink(missing_ok=True)
            self.conf_path.unlink(missing_ok=True)
            self.status_log_path.unlink(missing_ok=True)
            return

        if pki is None:
            raise RuntimeError("OpenVPN PKI bundle required when ovpn_enabled=True")

        resolved_dualstack = self.ipv6_dualstack if ipv6_dualstack is None else bool(ipv6_dualstack)
        if resolved_dualstack is None:
            resolved_dualstack = detect_host_ipv6_dualstack()

        rendered = render_openvpn_server_conf(
            interface_name=interface_name,
            ovpn_proto=ovpn_proto,
            ovpn_port=ovpn_port,
            ovpn_network=ovpn_network,
            tunnel_mode=tunnel_mode,
            allowed_cidrs=allowed_cidrs,
            dns_servers=dns_servers,
            dns_search_domain=dns_search_domain,
            pki=pki,
            mgmt_sock_path=self.mgmt_sock_path,
            status_log_path=self.status_log_path,
            admin_sock_path=self.admin_sock_path,
            ipv6_dualstack=resolved_dualstack,
        )
        self.conf_path.parent.mkdir(parents=True, exist_ok=True)
        flags = os.O_WRONLY | os.O_CREAT | os.O_TRUNC | getattr(os, "O_BINARY", 0)
        fd = os.open(str(self.conf_path), flags, 0o600)
        try:
            os.write(fd, rendered.encode("utf-8"))
        finally:
            os.close(fd)
        try:
            os.chmod(self.conf_path, 0o600)
        except OSError:
            pass

        self.controller.start_or_reload(
            self.conf_path,
            self.pid_path,
            rendered,
            mgmt_sock_path=self.mgmt_sock_path,
        )

    def list_online_clients(self) -> list[dict[str, Any]]:
        if not self.controller.is_running(self.pid_path):
            return []
        if not self.status_log_path.is_file():
            return []
        try:
            text = self.status_log_path.read_text(encoding="utf-8", errors="replace")
        except OSError:
            return []
        return parse_openvpn_status_log(text)

    def count_online_clients(self) -> int:
        return len(self.list_online_clients())

    def kill_user_sessions(self, username: str) -> bool:
        """Immediately terminate active OpenVPN session(s) for `username` via management socket."""
        if not username:
            return False
        return self.controller.kill_client(self.mgmt_sock_path, username)
